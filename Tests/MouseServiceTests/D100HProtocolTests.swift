import Foundation
import Testing
@testable import MouseService

@Test func d100hDetentRequestsMatchCapturedPackets() {
    #expect(D100HProtocol.readDetents() == Data([
        0xeb, 0x56, 0x24, 0xed, 0x9b, 0x6a, 0x06, 0x43,
        0x38, 0x90, 0xc4, 0x99, 0xa3, 0x60, 0xaa, 0xad, 0, 0, 0, 0
    ]))
    #expect(D100HProtocol.writeDetents(0xff).prefix(8) == Data([0x39, 0xb0, 0x56, 0xaf, 0xd3, 0x6f, 0x9a, 0xbf]))
    #expect(D100HProtocol.writeDetents(0).prefix(8) == Data([0x5f, 0x4e, 0x1d, 0x13, 0x71, 0xb2, 0x9a, 0x76]))
}

@Test func d100hDetentRepliesDistinguishReadWriteAndOtherReports() {
    let suffix: [UInt8] = [0x38, 0x90, 0xc4, 0x99, 0xa3, 0x60, 0xaa, 0xad, 0, 0, 0, 0]
    let read = Data([0x32, 0x29, 0x1e, 0x77, 0x2d, 0x1f, 0xf1, 0xa4] + suffix)
    let write = Data([0x99, 0xbf, 0x42, 0xca, 0x23, 0x54, 0xb0, 0xaf] + suffix)
    let other = Data([0x21, 0xf4, 0x5e, 0xb7, 0x1c, 0x35, 0x87, 0xab] + suffix)
    #expect(D100HProtocol.detentReply(read) == .read(0xff))
    #expect(D100HProtocol.detentReply(write) == .write(0))
    #expect(D100HProtocol.detentReply(other) == nil)
    #expect(D100HProtocol.detentReply(Data(read.prefix(19))) == nil)
}
